export function blueprintForCountry(countryName) {
  const raw = String(countryName || '').trim();
  if (COUNTRY_BLUEPRINTS[raw]) return COUNTRY_BLUEPRINTS[raw];
  const lowered = raw.toLowerCase();
  const alias = {
    'dr congo': 'DR Congo',
    'drc': 'DR Congo',
    'democratic republic of congo': 'DR Congo',
    'democratic republic of the congo': 'DR Congo',
    congo: 'DR Congo',
    'south africa': 'South Africa',
    'madagascar': 'Madagascar',
  };
  const mapped = alias[lowered];
  if (mapped && COUNTRY_BLUEPRINTS[mapped]) return COUNTRY_BLUEPRINTS[mapped];
  const fuzzy = Object.keys(COUNTRY_BLUEPRINTS).find((key) => key.toLowerCase() === lowered);
  if (fuzzy) return COUNTRY_BLUEPRINTS[fuzzy];
  return COUNTRY_BLUEPRINTS.Uganda;
}
