/**
 * Combinatorial long-tail keyword builder for safari/tourism SEO.
 * Focuses on traveler-intent, destination-specific, lower-competition phrases
 * (parks, experiences, trip styles) rather than ultra-competitive head terms alone.
 */
export function uniquePhrases(values) {
  const out = [];
  const seen = new Set();
  for (const value of values) {
    const phrase = String(value || '')
      .replace(/\u00a0/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
    if (!phrase) continue;
    const key = phrase.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(phrase);
  }
  return out;
}

function cross(left, right) {
  const out = [];
  for (const a of left) {
    for (const b of right) {
      out.push(`${a} ${b}`.replace(/\s+/g, ' ').trim());
    }
  }
  return out;
}

function withCountry(country, phrases) {
  const out = [];
  for (const phrase of phrases) {
    out.push(phrase);
    if (!new RegExp(`\\b${country}\\b`, 'i').test(phrase)) {
      out.push(`${phrase} ${country}`);
      out.push(`${country} ${phrase}`);
    }
  }
  return out;
}

