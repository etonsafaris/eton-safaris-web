/**
 * @param {{
 *   country: string,
 *   aliases?: string[],
 *   places: string[],
 *   themes: string[],
 *   extras?: string[],
 * }} spec
 */
export function buildKeywordUniverse(spec) {
  const country = spec.country;
  const aliases = spec.aliases || [];
  const places = spec.places || [];
  const themes = spec.themes || [];
  const extras = spec.extras || [];
  const countryNames = uniquePhrases([country, ...aliases]);

  const seeds = [];

  for (const name of countryNames) {
    seeds.push(
      `${name} safari`,
      `safari ${name}`,
      `${name} safari tours`,
      `safari tours ${name}`,
      `best safari in ${name}`,
      `best ${name} safari`,
      `${name} luxury safari`,
      `${name} budget safari`,
      `${name} safari packages`,
      `${name} safari holidays`,
      `${name} wildlife safari`,
      `wildlife safari ${name}`,
      `${name} safari itinerary`,
      `${name} safari cost`,
      `cost of safari in ${name}`,
      `how to book safari in ${name}`,
      `${name} safari lodges`,
      `${name} safari lodge`,
      `${name} national parks safari`,
      `things to do on safari in ${name}`,
      `${name} africa safari`,
      `africa safari ${name}`,
      `${name} safari vacation`,
      `${name} safari trip`,
      `${name} safari for families`,
      `${name} honeymoon safari`,
      `${name} photography safari`,
      `private safari ${name}`,
      `guided safari ${name}`,
      `tailor made safari ${name}`,
      `${name} safari from usa`,
      `${name} safari from uk`,
      `best time for safari in ${name}`,
      `best time to visit ${name} safari`,
      `${name} safari operators`,
      `${name} safari companies`,
      `${name} tour operator safari`
    );

    for (const place of places) {
      seeds.push(
        `${place} safari`,
        `safari ${place}`,
        `${place} ${name}`,
        `${name} ${place}`,
        `${place} safari ${name}`,
        `${name} safari ${place}`,
        `best ${place} safari`,
        `${place} wildlife safari`,
        `${place} game drive`,
        `${place} lodge`,
        `${place} safari lodge`,
        `${place} camping safari`,
        `${place} walking safari`,
        `visit ${place} ${name}`,
        `tour to ${place} ${name}`,
        `${place} itinerary`,
        `${place} safari package`,
        `${place} safari cost`,
        `${place} best time to visit`
      );
    }

    for (const theme of themes) {
      seeds.push(
        `${name} ${theme}`,
        `${theme} ${name}`,
        `best ${theme} in ${name}`,
        `${theme} tour ${name}`,
        `${theme} package ${name}`,
        `${theme} holiday ${name}`,
        `${theme} itinerary ${name}`,
        `${theme} cost ${name}`
      );
    }

    for (const experience of EXPERIENCE_MODIFIERS) {
      seeds.push(`${name} ${experience}`, `${experience} in ${name}`, `${experience} ${name}`);
    }

    for (const prefix of INTENT_PREFIXES) {
      for (const suffix of ['safari', 'safari tours', 'wildlife safari', 'tour package']) {
        const base = prefix ? `${prefix} ${name} ${suffix}` : `${name} ${suffix}`;
        seeds.push(base);
      }
    }

    for (const place of places.slice(0, 12)) {
      for (const suffix of INTENT_SUFFIXES.slice(0, 18)) {
        seeds.push(`${place} ${suffix}`);
        seeds.push(`${name} ${place} ${suffix}`);
      }
      for (const experience of EXPERIENCE_MODIFIERS.slice(0, 14)) {
        seeds.push(`${place} ${experience}`);
        seeds.push(`${experience} ${place} ${name}`);
      }
    }

    // Duration × destination long-tails (strong traveler intent, often lower competition).
    for (const days of ['3 day', '4 day', '5 day', '7 day', '8 day', '10 day', '12 day', '14 day', '21 day']) {
      seeds.push(
        `${days} ${name} safari`,
        `${days} safari ${name}`,
        `${days} ${name} tour`,
        `${days} wildlife safari ${name}`
      );
      for (const place of places.slice(0, 8)) {
        seeds.push(`${days} ${place} safari`, `${days} safari ${place}`);
      }
    }
  }

  // Place × theme combos
  for (const place of places) {
    for (const theme of themes) {
      seeds.push(`${place} ${theme}`, `${theme} ${place}`);
    }
  }

  seeds.push(...extras);
  seeds.push(...withCountry(country, extras));

  // Question / commercial investigation long-tails
  for (const name of countryNames) {
    seeds.push(
      `is ${name} good for safari`,
      `is ${name} safe for safari`,
      `why visit ${name} for safari`,
      `${name} vs kenya safari`,
      `${name} vs tanzania safari`,
      `${name} vs south africa safari`,
      `${name} safari vs botswana`,
      `where to stay on safari in ${name}`,
      `what animals to see in ${name}`,
      `${name} big five safari`,
      `${name} malaria safari advice`,
      `${name} safari visa requirements`,
      `${name} safari packing list`,
      `${name} dry season safari`,
      `${name} green season safari`,
      `${name} winter safari`,
      `${name} summer safari`
    );
  }

  return uniquePhrases(seeds);
}

