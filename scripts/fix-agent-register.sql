-- Agent signup: fix Agent_pkey collisions, allow public applications,
-- and keep registered_agents available for the admin Agents module.
-- Run once in the Supabase SQL editor.

create table if not exists public.registered_agents (
  id uuid primary key default gen_random_uuid(),
  name text,
  email text,
  phone text,
  country text,
  gender text,
  company text,
  address text,
  bio text,
  status text default 'Pending',
  created_at timestamptz default now()
);

alter table public.registered_agents add column if not exists name text;
alter table public.registered_agents add column if not exists email text;
alter table public.registered_agents add column if not exists phone text;
alter table public.registered_agents add column if not exists country text;
alter table public.registered_agents add column if not exists gender text;
alter table public.registered_agents add column if not exists company text;
alter table public.registered_agents add column if not exists address text;
alter table public.registered_agents add column if not exists bio text;
alter table public.registered_agents add column if not exists status text default 'Pending';
alter table public.registered_agents add column if not exists company_website text;
alter table public.registered_agents add column if not exists created_at timestamptz default now();
alter table public.registered_agents enable row level security;

drop policy if exists "Public insert registered_agents" on public.registered_agents;
create policy "Public insert registered_agents"
on public.registered_agents for insert to anon, authenticated
with check (true);

drop policy if exists "Authenticated read registered_agents" on public.registered_agents;
create policy "Authenticated read registered_agents"
on public.registered_agents for select to authenticated
using (true);

drop policy if exists "Authenticated update registered_agents" on public.registered_agents;
create policy "Authenticated update registered_agents"
on public.registered_agents for update to authenticated
using (true) with check (true);

do $$
declare
  seq text;
begin
  if to_regclass('public."Agent"') is not null then
    seq := pg_get_serial_sequence('public."Agent"', 'id');
    if seq is not null then
      perform setval(seq, (select coalesce(max(id), 1) from public."Agent"));
    end if;

    begin
      execute $sql$
        alter table public."Agent" alter column id drop identity if exists;
        alter table public."Agent" alter column id add generated by default as identity;
      $sql$;
    exception when others then
      null;
    end;

    alter table public."Agent" enable row level security;

    drop policy if exists "Public insert Agent" on public."Agent";
    create policy "Public insert Agent"
    on public."Agent" for insert to anon, authenticated
    with check (true);

    drop policy if exists "Authenticated read Agent" on public."Agent";
    create policy "Authenticated read Agent"
    on public."Agent" for select to authenticated
    using (true);

    drop policy if exists "Authenticated update Agent" on public."Agent";
    create policy "Authenticated update Agent"
    on public."Agent" for update to authenticated
    using (true) with check (true);
  end if;

  if to_regclass('public.registered_agents') is not null then
    seq := pg_get_serial_sequence('public.registered_agents', 'id');
    if seq is not null then
      perform setval(seq, (select coalesce(max(id::bigint), 1) from public.registered_agents));
    end if;
  end if;
end $$;
